
create table if not exists public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  user_id uuid references auth.users(id) on delete set null,
  requester_name text not null check (char_length(trim(requester_name)) between 2 and 120),
  requester_email text not null check (char_length(trim(requester_email)) between 5 and 254),
  company text,
  subject text not null check (char_length(trim(subject)) between 3 and 180),
  category text not null default 'general' check (category in ('general','account','business_profile','connections','messaging','billing','bug_report','other')),
  priority text not null default 'normal' check (priority in ('low','normal','high','urgent')),
  status text not null default 'open' check (status in ('open','in_progress','waiting_on_user','resolved','closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_reply_at timestamptz
);

create table if not exists public.support_replies (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.support_tickets(id) on delete cascade,
  sender_id uuid references auth.users(id) on delete set null,
  sender_name text not null,
  sender_email text,
  is_admin boolean not null default false,
  message text not null check (char_length(trim(message)) between 1 and 10000),
  created_at timestamptz not null default now()
);

create index if not exists support_tickets_user_id_idx on public.support_tickets(user_id);
create index if not exists support_tickets_status_updated_idx on public.support_tickets(status, updated_at desc);
create index if not exists support_replies_ticket_created_idx on public.support_replies(ticket_id, created_at);

alter table public.support_tickets enable row level security;
alter table public.support_replies enable row level security;

revoke all on public.support_tickets from anon, authenticated;
revoke all on public.support_replies from anon, authenticated;
grant insert on public.support_tickets to anon, authenticated;
grant select, insert, update on public.support_tickets to authenticated;
grant select, insert on public.support_replies to authenticated;

create policy "Public can submit support tickets"
on public.support_tickets for insert to anon, authenticated
with check (
  char_length(trim(requester_name)) between 2 and 120
  and char_length(trim(requester_email)) between 5 and 254
);

create policy "Users can read their own support tickets"
on public.support_tickets for select to authenticated
using ((select auth.uid()) = user_id);

create policy "Users can update their own ticket status only"
on public.support_tickets for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Admins can manage all support tickets"
on public.support_tickets for all to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Ticket owners can read replies"
on public.support_replies for select to authenticated
using (
  exists (
    select 1 from public.support_tickets t
    where t.id = ticket_id and t.user_id = (select auth.uid())
  )
);

create policy "Ticket owners can reply"
on public.support_replies for insert to authenticated
with check (
  sender_id = (select auth.uid())
  and is_admin = false
  and exists (
    select 1 from public.support_tickets t
    where t.id = ticket_id and t.user_id = (select auth.uid())
  )
);

create policy "Admins can manage all support replies"
on public.support_replies for all to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create or replace function public.touch_support_ticket()
returns trigger language plpgsql set search_path = ''
as $$
begin
  update public.support_tickets
  set updated_at = now(), last_reply_at = now()
  where id = new.ticket_id;
  return new;
end;
$$;

drop trigger if exists support_reply_touch_ticket on public.support_replies;
create trigger support_reply_touch_ticket
after insert on public.support_replies
for each row execute function public.touch_support_ticket();
